def apply_extras(sections: list[dict[str, Any]]) -> list[dict[str, Any]]:
    extra = extras_by_section()
    out = []
    seen: set[str] = set()
    for section in sections:
        more = extra.get(section["id"], [])
        known = {item["id"] for item in section["items"]}
        added = [item for item in more if item["id"] not in known]
        out.append({**section, "items": [*section["items"], *added]})
        seen.add(section["id"])
    if "electronics" not in seen:
        out.append(electronics_section())
    if "networks" not in seen:
        out.append(networks_section())
    return out
