neural(13, "practice", "Простая сеть без готового фреймворка", """
# Простая сеть без готового фреймворка

Один нейрон учится приближать правило «выход = 2 * вход». Это не распознавание картинок. Здесь видно, как вес ползёт к нужному числу.

```python
weight = 0.1
bias = 0.0
lr = 0.05
examples = [(-1, -2), (0, 0), (1, 2), (2, 4)]

for _epoch in range(50):
    for x, y in examples:
        pred = weight * x + bias
        # производная квадрата ошибки по предсказанию
        grad = 2 * (pred - y)
        weight -= lr * grad * x
        bias -= lr * grad

print(weight, bias)
```

`weight` должен оказаться около 2, `bias` около 0. Если `lr` сделать равным 1, числа часто разъезжаются. Это и есть слишком большой шаг.

Когда такой шаг понятен, библиотека вроде PyTorch делает то же для тысяч весов и сама считает backpropagation. Имеет смысл переходить к ней после этого примера, а не вместо него.
""")


