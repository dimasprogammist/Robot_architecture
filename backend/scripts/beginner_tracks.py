"""Write beginner handbook lessons and drop Canvas-only cross links."""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "learning"


def write(rel: str, lesson_id: str, title: str, category: str, section: str, order: int, description: str, body: str) -> None:
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    text = f"""---
id: {lesson_id}
title: {title}
category: {category}
section: {section}
order: {order}
description: {description}
tags: [{category}, основы]
technologies: []
related: []
---

{body.strip()}
"""
    path.write_text(text, encoding="utf-8")


def strip_canvas_sections() -> int:
    changed = 0
    for path in ROOT.rglob("*.md"):
        lines = path.read_text(encoding="utf-8").splitlines()
        out: list[str] = []
        skip = False
        touched = False
        for line in lines:
            if line.strip() == "## В Architecture Canvas":
                skip = True
                touched = True
                continue
            if skip and line.startswith("## "):
                skip = False
            if not skip:
                out.append(line)
        if touched:
            path.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")
            changed += 1
    return changed


