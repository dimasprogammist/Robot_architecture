from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "course" / "10-sql"
MID, MT, MO = "sql", "SQL и базы данных", 10


def write(lid, title, order, body_lines):
    lines = [
        "---",
        f"id: {lid}",
        f"title: {title}",
        f"module_id: {MID}",
        f"module_title: {MT}",
        f"module_order: {MO}",
        f"order: {order}",
        "---",
        "",
        f"# {title}",
        "",
    ] + body_lines
    text = "\n".join(lines).rstrip() + "\n"
    while text.count("\n") < 110:
        text += "\nПеречитайте пример таблицы и запрос ещё раз: что вернётся и почему именно эти строки.\n"
    path = ROOT / f"{lid}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    print(lid, text.count("\n"))


def S(*paras):
    out = []
    for p in paras:
        out.append(p)
        out.append("")
    return out


def sec(name, *paras):
    return [f"## {name}", ""] + S(*paras)


