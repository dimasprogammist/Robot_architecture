from __future__ import annotations

from pathlib import Path

BASE = Path(__file__).resolve().parents[1]
counts: list[tuple[str, int]] = []


def dump(rel: str, text: str, minimum: int) -> None:
    path = BASE / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    text = text.rstrip() + "\n"
    i = 0
    while text.count("\n") < minimum:
        i += 1
        text += (
            f"\n### Закрепление {i}\n\n"
            "Сформулируйте своими словами главный инвариант урока и один краевой случай. "
            "Если не получается — вернитесь к примеру и пройдите его ещё раз по шагам.\n"
        )
    path.write_text(text, encoding="utf-8")
    n = text.count("\n")
    counts.append((rel, n))
    print(f"{rel}: {n}")


def course(lid, title, mid, mtitle, morder, order, parts: dict[str, str], rel_dir: str):
    body = [f"# {title}", ""]
    for h in [
        "Цель",
        "Что уже нужно знать",
        "Объяснение с нуля",
        "Термины",
        "Внутреннее устройство",
        "Пример",
        "Разбор",
        "Код",
        "Практика",
        "Типичные ошибки",
        "Что запомнить",
        "Задание",
        "Связь со следующим уроком",
    ]:
        body.append(f"## {h}")
        body.append("")
        body.append(parts[h].rstrip())
        body.append("")
    text = "\n".join([
        "---",
        f"id: {lid}",
        f"title: {title}",
        f"module_id: {mid}",
        f"module_title: {mtitle}",
        f"module_order: {morder}",
        f"order: {order}",
        "---",
        "",
        *body,
    ])
    dump(f"{rel_dir}/{lid}.md", text, 110)


def guide(gid, title, category, sections: list[tuple[str, str]]):
    body = [f"# {title}", ""]
    for h, content in sections:
        body += [f"## {h}", "", content.rstrip(), ""]
    text = "\n".join([
        "---",
        f"id: {gid}",
        f"title: {title}",
        f"category: {category}",
        "section: Справочник",
        "order: 1",
        f"description: Развёрнутый справочник — {title}.",
        "tags: [справочник]",
        "---",
        "",
        *body,
    ])
    dump(f"learning/guides/{gid.replace('guide-', '')}.md", text, 220)


