def insertion_sort(a: list[int]) -> list[int]:
    a = a[:]
    for i in range(1, len(a)):
        key = a[i]
        j = i - 1
        while j >= 0 and a[j] > key:
            a[j + 1] = a[j]
            j -= 1
        a[j + 1] = key
    return a

assert insertion_sort([5, 2, 4, 6, 1, 3, 2]) == [1, 2, 2, 3, 4, 5, 6]
print(sorted([5, 2, 4, 6, 1, 3, 2]))  # в проде
