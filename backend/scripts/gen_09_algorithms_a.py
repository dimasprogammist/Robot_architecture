def brackets_ok(s: str) -> bool:
    pair = {')': '(', ']': '[', '}': '{'}
    st: list[str] = []
    for ch in s:
        if ch in '([{':
            st.append(ch)
        elif ch in ')]}':
            if not st or st[-1] != pair[ch]:
                return False
            st.pop()
    return not st

assert brackets_ok('(()[])') is True
assert brackets_ok('([)]') is False
